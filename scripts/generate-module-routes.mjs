
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve("src");
const MODS = path.join(SRC, "modules");
const MARK = "// @generated by scripts/sync-modules.mjs - DO NOT EDIT";
const STATE = path.resolve("src/generated/.generated-files.json");

const cfg = JSON.parse(
  fs.readFileSync(path.resolve("src/modules.config.json"), "utf8"),
);
const all = fs
  .readdirSync(MODS)
  .filter((d) => fs.existsSync(path.join(MODS, d, "manifest.ts")));
const envList = process.env.MODULES?.split(",")
  .map((s) => s.trim())
  .filter(Boolean);
const wanted = envList ?? (cfg.enabled === "*" ? all : cfg.enabled);
const enabled = wanted.filter((m) => !(cfg.disabled ?? []).includes(m));

const fail = (m) => {
  console.error("\n[modules] ERROR: " + m + "\n");
  process.exit(1);
};
for (const m of enabled)
  if (!all.includes(m))
    fail(`unknown module "${m}". Available: ${all.join(", ")}`);

for (const m of enabled) {
  const txt = fs.readFileSync(path.join(MODS, m, "manifest.ts"), "utf8");
  const req =
    /requires\s*:\s*\[([^\]]*)\]/
      .exec(txt)?.[1]
      .match(/["'`]([^"'`]+)["'`]/g) ?? [];
  for (const r of req.map((s) => s.slice(1, -1)))
    if (!enabled.includes(r))
      fail(`module "${m}" requires "${r}", which is not enabled.`);
}

fs.mkdirSync(path.dirname(STATE), { recursive: true });
if (fs.existsSync(STATE))
  for (const f of JSON.parse(fs.readFileSync(STATE, "utf8"))) {
    fs.rmSync(f, { force: true });
    let d = path.dirname(f);
    while (
      d.startsWith(path.join(SRC, "app")) &&
      d !== path.join(SRC, "app") &&
      fs.readdirSync(d).length === 0
    ) {
      fs.rmdirSync(d);
      d = path.dirname(d);
    }
  }

const written = [];
const routes = [];
const walk = (dir) =>
  fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)],
    );

for (const m of enabled) {
  const rdir = path.join(MODS, m, "routes");
  if (!fs.existsSync(rdir)) continue;
  for (const file of walk(rdir)) {
    const rel = path.relative(rdir, file).split(path.sep).join("/");
    const target = path.join(SRC, "app", rel);
    if (
      fs.existsSync(target) &&
      !fs.readFileSync(target, "utf8").startsWith(MARK)
    )
      fail(
        `${path.relative(
          SRC,
          target,
        )} already exists as a hand-written file (module "${m}" conflicts).`,
      );
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const name = path.basename(file);
    const importPath = `@/modules/${m}/routes/${rel}`.replace(/\.tsx?$/, "");
    const isPage =
      /^(page|layout|loading|error|not-found|template|default)\.tsx?$/.test(
        name,
      );
    const body = isPage
      ? `${MARK}\nexport { default } from "${importPath}";\n`
      : `${MARK}\nexport * from "${importPath}";\n`; // route.ts handlers
    // Next segment config (dynamic, revalidate...) must be literal in the file itself,
    // so modules declare it in routes/.../segment.json -> not needed yet.
    fs.writeFileSync(target, body);
    written.push(target);
    if (name.startsWith("page."))
      routes.push([("/" + path.dirname(rel)).replace(/\/\.$/, ""), m]);
  }
}
fs.writeFileSync(STATE, JSON.stringify(written, null, 1));

const out = `${MARK}
import type { ModuleManifest } from "@/core/types";
${enabled
  .map((m, i) => `import m${i} from "@/modules/${m}/manifest";`)
  .join("\n")}

export const enabledModuleIds = ${JSON.stringify(enabled)} as const;
export const moduleManifests: readonly ModuleManifest[] = [${enabled
  .map((_, i) => "m" + i)
  .join(", ")}];
/** [urlPattern, moduleId] - used by ModuleRouteGuard */
export const moduleRoutes: readonly (readonly [string, string])[] = ${JSON.stringify(
  routes,
)};
`;
fs.writeFileSync(path.join(SRC, "generated/modules.ts"), out);
console.log(
  `[modules] enabled: ${enabled.join(", ") || "(none)"} | routes: ${
    written.length
  }`,
);
